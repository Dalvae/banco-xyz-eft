CREATE TABLE IF NOT EXISTS customer_profile (
  id VARCHAR(40) PRIMARY KEY,
  display_name VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS account (
  id BIGINT PRIMARY KEY,
  owner VARCHAR(40) NOT NULL,
  display_name VARCHAR(120) NOT NULL,
  masked_number VARCHAR(40) NOT NULL,
  currency VARCHAR(3) NOT NULL,
  balance DECIMAL(19,2) NOT NULL CHECK (balance >= 0),
  origin VARCHAR(80) NOT NULL,
  CONSTRAINT fk_account_owner FOREIGN KEY(owner) REFERENCES customer_profile(id)
);

CREATE TABLE IF NOT EXISTS movement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL,
  movement_date DATE NOT NULL,
  movement_type VARCHAR(30) NOT NULL,
  amount DECIMAL(19,2) NOT NULL,
  description VARCHAR(300) NOT NULL,
  source VARCHAR(100) NOT NULL,
  source_line INT,
  operation_id VARCHAR(36),
  CONSTRAINT fk_movement_account FOREIGN KEY(account_id) REFERENCES account(id),
  CONSTRAINT uq_movement_source_line UNIQUE(source, source_line),
  CONSTRAINT uq_movement_operation UNIQUE(operation_id)
);

CREATE TABLE IF NOT EXISTS withdrawal_idempotency (
  idempotency_key VARCHAR(120) PRIMARY KEY,
  operation_id VARCHAR(36) NOT NULL UNIQUE,
  account_id BIGINT NOT NULL,
  amount DECIMAL(19,2) NOT NULL,
  balance_after DECIMAL(19,2) NOT NULL,
  currency VARCHAR(3) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_withdrawal_account FOREIGN KEY(account_id) REFERENCES account(id)
);

-- outbox: el retiro guarda aca su evento en la misma transaccion y despues se manda a kafka
-- si kafka esta caido queda enviado=false y se reintenta hasta que vuelva
CREATE TABLE IF NOT EXISTS evento_pendiente (
  operation_id VARCHAR(36) PRIMARY KEY,
  cuenta_id BIGINT NOT NULL,
  titular VARCHAR(40) NOT NULL,
  monto DECIMAL(19,2) NOT NULL,
  saldo DECIMAL(19,2) NOT NULL,
  fecha TIMESTAMP WITH TIME ZONE NOT NULL,
  enviado BOOLEAN DEFAULT FALSE NOT NULL,
  intentos INT DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS legacy_import_audit (
  source VARCHAR(100) NOT NULL,
  source_line INT NOT NULL,
  status VARCHAR(20) NOT NULL,
  reason VARCHAR(80),
  raw_account VARCHAR(40),
  PRIMARY KEY(source, source_line)
);

